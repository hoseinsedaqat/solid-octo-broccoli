#!/usr/bin/env node
/**
 * Generates apps/worker/seeds/seed.sql from the canonical data in
 * `shared/src/constants.ts` (single source of truth — no hand-copied SQL).
 *
 *   npm run db:generate-seed
 *
 * Rules enforced here:
 *  - equipment prices stay NULL (never invented);
 *  - F-22 / F-35 stay duplicated across their two categories (no merging);
 *  - starter pack numbers come from the design document.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const constantsPath = resolve(here, '../shared/src/constants.ts');
const C = await import(pathToFileURL(constantsPath).href);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const num = (n) => (n === null || n === undefined ? 'NULL' : String(n));
const rows = [];
const push = (s) => rows.push(s);

push(`-- World War seed — GENERATED by scripts/gen-seed.mjs. Do not edit by hand.`);
push(`-- Prices are intentionally NULL: unpriced equipment is not purchasable until the admin sets a price.`);
// no explicit BEGIN/COMMIT: every statement is an idempotent INSERT OR IGNORE, and
// `wrangler d1 execute --local` rejects raw transaction statements in --file mode.

// 1) categories -----------------------------------------------------------
const catIds = {};
let sortOrder = 1;
for (const c of C.EQUIPMENT_CATEGORIES) {
  catIds[c.key] = sortOrder;
  push(
    `INSERT OR IGNORE INTO equipment_categories (id, key, label_fa, shop_label_fa, emoji, role, power_weight, sort_order, is_active)
     VALUES (${sortOrder}, ${q(c.key)}, ${q(c.labelFa)}, ${q(c.shopLabelFa)}, ${q(c.emoji)}, ${q(c.role)}, ${num(C.DEFAULT_CATEGORY_POWER_WEIGHTS[c.key] ?? 0)}, ${sortOrder}, 1);`,
  );
  sortOrder++;
}

// 2) equipment templates (price NULL, points NULL until admin fills) -----
const tplIds = {};
let tid = 1;
const perCategory = {};
for (const [catKey, items] of Object.entries(C.STARTER_PACK)) {
  perCategory[catKey] = [];
  for (const it of items) {
    tplIds[`${catKey}:${it.code}`] = tid;
    perCategory[catKey].push({ id: tid, code: it.code, quantity: it.quantity });
    push(
      `INSERT OR IGNORE INTO equipment_templates (id, category_id, code, name_fa, unit_fa, price, attack_points, defense_points, description, is_active, is_for_sale, purchase_limit_per_cycle, maintenance_per_unit)
       VALUES (${tid}, ${catIds[catKey]}, ${q(it.code)}, ${q(it.nameFa)}, ${q(it.unitFa)}, NULL, NULL, NULL, ${q(it.descriptionFa)}, 1, 1, NULL, NULL);`,
    );
    tid++;
  }
}

// 3) starter template ----------------------------------------------------
const E = C.STARTER_ECONOMY;
push(
  `INSERT OR IGNORE INTO starter_templates (id, name, description, treasury, factory_income, mine_income, income_cycle_seconds, is_default, is_active)
   VALUES (1, 'بسته اولیه استاندارد', 'مقادیر مندرج در سند طراحی بازی', ${E.treasury}, ${E.factoryIncome}, ${E.mineIncome}, ${E.incomeCycleSeconds}, 1, 1);`,
);
let sid = 1;
for (const items of Object.values(perCategory)) {
  for (const it of items) {
    push(
      `INSERT OR IGNORE INTO starter_template_items (id, starter_template_id, equipment_template_id, quantity)
       VALUES (${sid++}, 1, ${it.id}, ${it.quantity});`,
    );
  }
}

// 4) settings ------------------------------------------------------------
const settings = {
  battle_params: C.DEFAULT_BATTLE_PARAMS,
  profile_rules: C.DEFAULT_PROFILE_RULES,
  diplomacy_rules: C.DEFAULT_DIPLOMACY_RULES,
  feature_flags: C.FEATURE_FLAGS,
  ranking_weights: C.DEFAULT_RANKING_WEIGHTS,
  branding: C.DEFAULT_BRANDING,
  quota_guard: C.DEFAULT_QUOTA_GUARD,
};
for (const [k, v] of Object.entries(settings)) {
  push(
    `INSERT OR IGNORE INTO game_settings (key, value, value_type, description)
     VALUES (${q(k)}, ${q(JSON.stringify(v))}, 'json', 'seed default');`,
  );
}
const economy = {
  economy_rules: C.DEFAULT_ECONOMY_RULES,
  starter_economy: E,
};
for (const [k, v] of Object.entries(economy)) {
  push(
    `INSERT OR IGNORE INTO economy_settings (key, value, value_type, description)
     VALUES (${q(k)}, ${q(JSON.stringify(v))}, 'json', 'seed default');`,
  );
}


const totalItems = Object.values(C.STARTER_PACK).reduce((s, arr) => s + arr.length, 0);
push(`-- ${C.EQUIPMENT_CATEGORIES.length} categories, ${totalItems} equipment templates`);

mkdirSync(dirname(resolve(here, '../apps/worker/seeds/seed.sql')), { recursive: true });
writeFileSync(resolve(here, '../apps/worker/seeds/seed.sql'), rows.join('\n') + '\n', 'utf8');
console.log(
  `seed.sql written: ${C.EQUIPMENT_CATEGORIES.length} categories, ${totalItems} templates, starter treasury ${E.treasury}, income ${E.factoryIncome}+${E.mineIncome}`,
);
